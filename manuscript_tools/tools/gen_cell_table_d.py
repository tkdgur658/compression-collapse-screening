"""Pass 32 (journal review 2, item A-5, [internal decision] = [id], 2026-10-16): full 11 x 6 x 3 cell table of
setting D (mean Dice retention over the analysed splits, L80 and L90 marks) -> tables/tb_app_cells_d.tex.

Records: results/qdeploy/records_p32/*.json, a read-only copy (scp, 2026-10-16) of the frozen F3 records
<WORK>/qdeploy/out/items/*.json; per-file sha256 of the copy equals the server listing
(iso/s4/qdeploy/RECORDS_P32_server_sha.txt). Rows and cells come from the frozen functions ckpt_rows and cell_table of
iso/s4/qdeploy/qdeploy_analyze.py (sha256 f93895df..., FROZEN_SHA256SUMS), unchanged. Exclusion as in
RESULT_QDEPLOY.json "excluded" (malunet__isic18__k4; no E1 failure). The script checks that its collapsed cells equal
RESULT_QDEPLOY.json table_i.L80.D and L90.D collapsed_cells and stops otherwise.
Run:  python -s tools/gen_cell_table_d.py
"""
import glob, hashlib, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
QD = os.path.normpath(os.path.join(ROOT, "..", "results", "qdeploy"))
SHA_ANALYZE = "f93895df79de58d3e612f1dfeea314fef4329bfa3ca87663f8db4b2f0a6166e2"  # released (path-redacted) copy; original f93895df79de58d3e612f1dfeea314fef4329bfa3ca87663f8db4b2f0a6166e2
SHA_RESULT = "a5d323e7c52fa375f2b1c69f3770f7393025e8a82286be9b37f8ac6a481f971e"
OUT = os.path.join(ROOT, "tables", "tb_app_cells_d.tex")
MODELS = [("pbe", "PBE-Net"), ("maresunet", "MAResUNet"), ("utanet", "UTANet"), ("mk_unet", "MK-UNet"),
          ("mhorunet", "MHorUNet"), ("tinyunet", "TinyU-Net"), ("ucmnet", "UCMNet"), ("lbunet", "LB-UNet"),
          ("cmunext", "CMUNeXt"), ("egeunet", "EGE-UNet"), ("malunet", "MALUNet")]
DATASETS = [("PH2", "PH2"), ("isic17", "ISIC17"), ("isic18", "ISIC18"), ("kvasir", "Kvasir"), ("cvc", "CVC"), ("etis", "ETIS")]
OPS = ["D_w4", "D_a6", "D_l50"]


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    if sha(os.path.join(QD, "qdeploy_analyze.py")) != SHA_ANALYZE or sha(os.path.join(QD, "result", "RESULT_QDEPLOY.json")) != SHA_RESULT:
        sys.exit("sha256 mismatch")
    srv = dict((l.split()[1], l.split()[0]) for l in open(os.path.join(QD, "RECORDS_P32_server_sha.txt")))
    files = sorted(glob.glob(os.path.join(QD, "records_p32", "*.json")))
    assert len(files) == 330 and all(srv[os.path.basename(f)] == sha(f) for f in files), "record copy differs from server listing"
    sys.dont_write_bytecode = True
    sys.path.insert(0, QD)
    import qdeploy_analyze as A
    res = json.load(open(os.path.join(QD, "result", "RESULT_QDEPLOY.json"), encoding="utf8"))
    recs = [json.load(open(f, encoding="utf8")) for f in files]
    excl = set(res["excluded"]); excl_ds = set(res["E1_failed_excluded_from_D_S"])
    use = [r for r in recs if r["tag"] not in excl]
    assert len(use) == res["n_used"] == 329
    cells = A.cell_table(A.ckpt_rows(use, A.DEPL, excl_ds))
    assert len(cells) == 198
    for lab, thr in (("L80", 0.8), ("L90", 0.9)):
        mine = sorted("%s|%s|%s" % k for k, v in cells.items() if v["mean_R"] < thr)
        assert mine == res["table_i"][lab]["D"]["collapsed_cells"], lab
    n80 = sum(v["mean_R"] < 0.8 for v in cells.values()); n90 = sum(v["mean_R"] < 0.9 for v in cells.values())
    assert (n80, n90) == (80, 107)

    def fmt(m, d, o):
        v = cells[(m, d, o)]
        s = "%.3f" % v["mean_R"]
        if v["mean_R"] < 0.8:
            s = r"\textbf{%s}" % s
        elif v["mean_R"] < 0.9:
            s = s + r"$^{\dagger}$"
        if v["n_splits"] < 5:
            s = s + r"$^{%d}$" % v["n_splits"]
        return s

    rows = []
    for m, mn in MODELS:
        for j, (d, dn) in enumerate(DATASETS):
            rows.append(r" %s & %s & %s \\" % (mn if j == 0 else "", dn, " & ".join(fmt(m, d, o) for o in OPS)))
        rows.append(r"\hline")
    half = 33
    left, right = [], []
    flat = [(m, mn, j, d, dn) for m, mn in MODELS for j, (d, dn) in enumerate(DATASETS)]
    def line(t):
        m, mn, j, d, dn = t
        return "%s & %s & %s" % (mn if j == 0 or t is flat[half] else "", dn, " & ".join(fmt(m, d, o) for o in OPS))
    body = []
    for i in range(half):
        body.append(" " + line(flat[i]) + " & " + line(flat[half + i]) + r" \\")
    tex = r"""%% GENERATED by tools/gen_cell_table_d.py from the read-only copy of the frozen F3 records (iso/s4/qdeploy/records_p32, sha listing RECORDS_P32_server_sha.txt) with qdeploy_analyze.py (sha256 %s), do not edit by hand.
%% Checked: collapsed cells equal RESULT_QDEPLOY.json table_i L80.D (80) and L90.D (107).
\begin{table*}[tp]
\centering
\caption{\label{tab:app_cells_d}Mean Dice retention of every cell of setting D (deployed graph, per-channel w4, per-tensor a6, layer-wise one-shot l50), averaged over five splits. Bold marks a collapsed cell under L80 (below 0.8), and $^{\dagger}$ marks a cell between 0.8 and 0.9, collapsed under L90 only. A superscript 4 marks the one cell with four analysed splits (MALUNet, ISIC 2018). In total, 80 of 198 cells collapse under L80 and 107 under L90.}
\scriptsize
\begin{tblr}{colspec={X[1.3,l] X[0.8,l] X[0.8,c] X[0.8,c] X[0.8,c] X[1.3,l] X[0.8,l] X[0.8,c] X[0.8,c] X[0.8,c]}, width=\textwidth, colsep=1.5pt, rowsep=0pt, vline{6}={solid}}
\hline
 Model & Dataset & w4 & a6 & l50 & Model & Dataset & w4 & a6 & l50 \\
\hline
%s
\hline
\end{tblr}
\end{table*}
""" % (SHA_ANALYZE, "\n".join(body))
    io.open(OUT, "w", encoding="utf8", newline="\n").write(tex)
    print("wrote", OUT, "L80", n80, "L90", n90)


if __name__ == "__main__":
    main()
