"""Pass 31 ([internal decision], 2026-10-16): Jetson Nano latency after PREREG_JETSON AMENDMENT 1 (clocks fixed by the user).

Reads both result files and checks their sha256 prefixes:
  results/jetson/JETSON_RESULT.json     (first run, frozen rule, sha ed3e719e..., 0 of 11 reportable)
  results/jetson/JETSON_RESULT_A1.json  (amendment run a1, sha 7c589623..., 6 models measured)
Writes tables/tb_app_jetson.tex (Appendix app:jetson, both runs) and prints the Table 2 Jetson column
(one decimal, as the RTX column). tools/gen_jetson_app.py (Pass 29, first run only) is kept unchanged.

Run from manuscript_cleanup/:  python -s tools/gen_jetson_a1.py           (write + print column)
                                python -s tools/gen_jetson_a1.py --check   (print only)
"""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JDIR = os.path.normpath(os.path.join(ROOT, "..", "results", "jetson"))
SRC0, SHA0 = os.path.join(JDIR, "JETSON_RESULT.json"), "c7ff2ee6"
SRC1, SHA1 = os.path.join(JDIR, "JETSON_RESULT_A1.json"), "7c589623"
OUT = os.path.join(ROOT, "tables", "tb_app_jetson.tex")
ORDER = ["pbe", "maresunet", "utanet", "mk_unet", "mhorunet", "tinyunet", "ucmnet", "lbunet", "cmunext", "egeunet", "malunet"]
DISPLAY = {"pbe": "PBE-Net", "maresunet": "MAResUNet", "utanet": "UTANet", "mk_unet": "MK-UNet", "mhorunet": "MHorUNet",
           "tinyunet": "TinyU-Net", "ucmnet": "UCMNet", "lbunet": "LB-UNet", "cmunext": "CMUNeXt", "egeunet": "EGE-UNet",
           "malunet": "MALUNet"}


def load(path, prefix):
    raw = open(path, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    if not sha.startswith(prefix):
        sys.exit("sha256 mismatch for %s: %s" % (path, sha))
    return json.loads(raw)


def first_run(v):
    r = v.get("reason") or ""
    if r.startswith("unstable"):
        meds = [v["attempts"][a]["discarded_block_stats"]["median_ms"] for a in v["discarded_attempts"]]
        return "a", "Discarded, clock changed in every block (%s)" % " / ".join("%.1f" % x for x in meds)
    if r.startswith("TensorRT"):
        return "b", "TensorRT 8.2.1 rejected the ONNX graph"
    if r.startswith("ONNX opset 11 export failed"):
        return "c", "No ONNX opset 11 export of an operator"
    raise ValueError(r)


def main():
    d0, d1 = load(SRC0, SHA0), load(SRC1, SHA1)
    M0, M1 = d0["models"], d1["models"]
    assert all(M0[k]["status"] == "n.m." for k in ORDER)
    col, rows = {}, []
    for k in ORDER:
        code, first = first_run(M0[k])
        if k in M1:
            v = M1[k]
            assert v["status"] == "measured" and v["n_timed"] == 50 and code == "a", (k, v["status"], code)
            col[k] = "%.1f" % v["median_ms"]
            a1 = "%.1f (%.2f)" % (v["median_ms"], v["iqr_ms"])
        else:
            assert code in ("b", "c"), (k, code)
            col[k] = "n.m.$^%s$" % code
            a1 = "not attempted"
        rows.append(" %s & %s & %s \\\\" % (DISPLAY[k], first, a1))
    L = ["% Generated by tools/gen_jetson_a1.py from results/jetson/JETSON_RESULT.json (sha ed3e719e...) and JETSON_RESULT_A1.json (sha 7c589623...). Do not edit by hand.",
         "% Before (Pass 29): table of the first run only, generated by tools/gen_jetson_app.py (kept).",
         "\\begin{table}[t]", "\\centering",
         "\\caption{\\label{tab:app_jetson}Jetson Nano latency of the eleven models (TensorRT 8.2.1 FP16, fused graph, ONNX opset 11, batch one, $256\\times256$ input, warm-up 10 and 50 timed runs, GPU compute time). "
         "In the first run under the frozen pre-registration, the unfixed clocks changed during every block, so no value was reportable, with the block medians in parentheses kept as a record only. "
         "The amendment run fixed the clocks with \\texttt{jetson\\_clocks}, a disclosed change from the frozen pre-registration made after the discarded values had been seen. "
         "Values are the median with the interquartile range in parentheses, in ms. The five models that failed in the toolchain were not attempted again.}",
         "\\footnotesize",
         "\\begin{tblr}{colspec={Q[l] X[l] Q[c]}, width=\\linewidth, colsep=3pt}",
         "\\hline",
         " Model & First run (frozen rule) & Amendment run, median (IQR) \\\\",
         "\\hline"] + rows + ["\\hline", "\\end{tblr}", "\\end{table}", ""]
    tex = "\n".join(L)
    if "--check" not in sys.argv:
        open(OUT, "w", encoding="utf-8", newline="\n").write(tex)
        print("wrote", OUT)
    print(json.dumps(col))


if __name__ == "__main__":
    main()
