# Generate tables/tb_app_abl.tex (Appendix app:abl) from results/abl/result/abl_result.json only
# (F4 one-factor ablation, PREREG_ABL.md frozen sha 6a2c3341, decision run once 2026-10-17 by abl/tools/run_decide.sh).
# Usage: python tools/gen_abl_table.py   (run from manuscript_cleanup/)
import json, os, hashlib, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.normpath(os.path.join(ROOT, "..", "results", "abl", "result", "abl_result.json"))
OUT = os.path.join(ROOT, "tables", "tb_app_abl.tex")
EXPECTED = "6ffee1b5b9dd70653be0ee215b603ed2364431050f01b002bbce3c4ac8947989"
VAR = [("pbe_idskip", "Plain skip instead of predictive-residual skip"),
       ("pbe_lam0", "Matching loss off ($\\lambda_s=0$)"),
       ("pbe_mbv2", "MobileNetV2 block instead of the feature block$^{a}$"),
       ("pbe_se", "Squeeze-and-excitation gate instead of the channel gate$^{b}$")]
DS = [("cvc", "CVC-ClinicDB"), ("isic17", "ISIC 2017"), ("isic18", "ISIC 2018")]


def f(x, d=4):
    return ("+" if x >= 0 else "$-$") + f"{abs(x):.{d}f}"


def main():
    raw = open(SRC, "rb").read()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        sys.exit("abl_result.json sha differs from the decided file")
    d = json.loads(raw)
    assert d["family_size"] == 12 and d["n_effect_components"] == 0
    L = ["% Generated by tools/gen_abl_table.py from results/abl/result/abl_result.json (sha 6ffee1b5...). Do not edit by hand.",
         "\\begin{table}[tp]", "\\centering",
         "\\caption{\\label{tab:app_abl}Pre-registered one-factor ablation of PBE-Net on three datasets over five splits. "
         "Difference is the mean paired difference of test IoU (variant minus full PBE-Net) with its 95\\% $t$ interval. "
         "Holm correction runs over all 12 comparisons. "
         "A component counts as effective only if its replacement lowers IoU significantly on at least two of the three datasets, which no replacement did.}",
         "\\scriptsize",
         "\\begin{tblr}{colspec={X[2.6,l] Q[l] Q[c] Q[c] Q[c]}, width=\\linewidth, colsep=2pt}",
         "\\hline",
         " Replacement & Dataset & Difference [95\\% CI] & raw $p$ & Holm $p$ \\\\",
         "\\hline"]
    for v, name in VAR:
        for i, (ds, dn) in enumerate(DS):
            c = d["cells"][f"{v}|{ds}"]
            assert not c["sig_drop"] and not c["sig_up"]
            ci = c["ci95"]
            L.append(f" {name if i == 0 else ''} & {dn} & {f(c['mean_diff'])} [{f(ci[0])}, {f(ci[1])}] & {c['p_raw']:.3f} & {c['p_holm']:.3f} \\\\")
        L.append("\\hline")
    # Pass 35 (reviewer 3 round 4, must-fix 4): params_inference of abl_result.json is counted on the built training graph
    # (unfused re-parameterizable branches) without the training-only heads (trainer.py n_inf), so footnote b now says
    # "in the training graph"; before "(1{,}394{,}753 against 1{,}334{,}337 at inference)". Values asserted from the json.
    assert {d["cells"][f"pbe_se|{ds}"]["params_inference"] for ds, _ in DS} == {1394753}
    assert {d["cells"][f"pbe_idskip|{ds}"]["params_inference"] for ds, _ in DS} == {1334337}
    L += ["\\end{tblr}",
          "\\par\\smallskip{\\scriptsize $^{a}$The block has about twice the FLOPs of the full model (6.778 against 3.370\\,G), because the code fixes its hidden width. "
          "$^{b}$The gate adds 60{,}416 parameters (1{,}394{,}753 against 1{,}334{,}337 in the training graph, without the training-only boundary heads).}",
          "\\end{table}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
