"""Pass 32 (journal review 2, item A-1, [internal decision] = [id], 2026-10-16): generate the appendix tables of the
post hoc robustness analysis of the label-free screen (rule R1) from results/qdeploy/tau/Q_ROBUST.json.

Source: Q_ROBUST.json (sha256 must be 581598a8...e5c01c), written on the server by q_robust.py (sha256 must be
d58a409c...4d98) from the frozen F3 QDEPLOY records with the frozen row, label and AUC functions of qdeploy_analyze.py.
Everything here is post hoc, outside the pre-registration. The script refuses to write if a hash differs.

Writes tables/tb_app_qr_auc.tex, tb_app_qr_heldout.tex, tb_app_qr_model.tex, tb_app_qr_miss.tex.
Run:  python -s tools/gen_q_robust_tables.py          (writes)
      python -s tools/gen_q_robust_tables.py --check  (prints, writes nothing)
"""
import hashlib, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
TAU = os.path.normpath(os.path.join(ROOT, "..", "results", "qdeploy", "tau"))
JSON_SHA = "581598a8101cb9ebc1a5fe975883a23539ed8ac87f31532a19f28a76cbb5e01c"
SCRIPT_SHA = "fc89505b5a970ce648693bb4b085040b88414ceee95654b2ca87346ac361b850"
MODELS = [("pbe", "PBE-Net"), ("maresunet", "MAResUNet"), ("utanet", "UTANet"), ("mk_unet", "MK-UNet"),
          ("mhorunet", "MHorUNet"), ("tinyunet", "TinyU-Net"), ("ucmnet", "UCMNet"), ("lbunet", "LB-UNet"),
          ("cmunext", "CMUNeXt"), ("egeunet", "EGE-UNet"), ("malunet", "MALUNet")]
DATASETS = [("PH2", "PH2"), ("isic17", "ISIC 2017"), ("isic18", "ISIC 2018"), ("kvasir", "Kvasir-SEG"),
            ("cvc", "CVC-ClinicDB"), ("etis", "ETIS-Larib")]
OPS = [("D_w4", "w4"), ("D_a6", "a6"), ("D_l50", "l50")]
HDR = "%% GENERATED by tools/gen_q_robust_tables.py from results/qdeploy/tau/Q_ROBUST.json (sha256 %s), do not edit by hand.\n%% Post hoc (outside the pre-registration).\n"


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def f3(x):
    return "%.3f" % x


def ci(d):
    return "%s [%s, %s]" % (f3(d["point"]), f3(d["ci95"][0]), f3(d["ci95"][1]))


def main():
    jp, sp = os.path.join(TAU, "Q_ROBUST.json"), os.path.join(TAU, "q_robust.py")
    if sha(jp) != JSON_SHA or sha(sp) != SCRIPT_SHA:
        sys.exit("sha256 mismatch: Q_ROBUST.json %s, q_robust.py %s" % (sha(jp), sha(sp)))
    d = json.load(open(jp, encoding="utf8"))
    h = HDR % JSON_SHA
    # consistency checks against the numbers printed in the text
    assert abs(d["tau_split1_agreement"] - 0.7378795710083479) < 1e-12
    assert d["missed"]["n"] == 29 and d["false_alarms"]["n"] == 43
    assert d["per_model_all_splits"]["pbe"] == {"n": 90, "collapsed": 52, "collapsed_flagged": 49, "intact": 38, "intact_flagged": 0}
    assert sum(sum(v.values()) for v in d["missed"]["by_model_setting"].values()) == 29
    assert sum(sum(v.values()) for v in d["false_alarms"]["by_model_setting"].values()) == 43
    out = {}

    # (1) AUC by operator with cell-level cluster bootstrap
    rows = []
    for s, lab in OPS + [("pooled_D", "pooled")]:
        a = d["auc"][s]
        rows.append(r" %s & %d & %d & %s & %s & %s \\" % (lab, a["agree"]["n_pos"], a["agree"]["n_neg"], ci(a["agree"]), ci(a["fg"]), ci(a["sqnr"])))
    out["tb_app_qr_auc.tex"] = h + r"""\begin{table}[tp]
\centering
\caption{\label{tab:app_qr_auc}Collapse AUC by operator in setting D under L80, post hoc (outside the pre-registration). Collapsed and healthy count checkpoint-settings over all five splits. Brackets give 95\%% percentile intervals of a cluster bootstrap that resamples the 66 model-dataset cells ($B = %d$, seed %d). Each point estimate pools the checkpoint-settings of all five splits, whereas the main text reports the mean of the five within-split AUCs. The pooled row pools the three operators, as in the pre-registered analysis.}
\scriptsize
\begin{tblr}{colspec={Q[l] Q[c] Q[c] Q[c] Q[c] Q[c]}, colsep=3pt}
\hline
 Operator & Collapsed & Healthy & Output agreement & Foreground ratio & Output SQNR \\
\hline
%s
\hline
\end{tblr}
\end{table}
""" % (d["B"], d["seed"], "\n".join(rows))

    # (2) held-out thresholds
    rows = [r" \SetCell[c=6]{l} Leave one model out (threshold selected on split 1 of the other ten models) & & & & & \\"]
    for m, mn in MODELS:
        v = d["LOMO"][m]
        rows.append(r" & %s & %s & %d & %d & %s / %s \\" % (mn, f3(v["tau_agreement"]), v["n_pos"], v["n_neg"], f3(v["sens"]), f3(v["spec"])))
    v = d["LOMO_pooled"]
    rows.append(r" & Pooled & -- & %d & %d & %s / %s \\" % (v["n_pos"], v["n_neg"], f3(v["sens"]), f3(v["spec"])))
    rows.append(r" \SetCell[c=6]{l} Leave one dataset out (threshold selected on split 1 of the other five datasets) & & & & & \\")
    for k, dn in DATASETS:
        v = d["LODO"][k]
        rows.append(r" & %s & %s & %d & %d & %s / %s \\" % (dn, f3(v["tau_agreement"]), v["n_pos"], v["n_neg"], f3(v["sens"]), f3(v["spec"])))
    v = d["LODO_pooled"]
    rows.append(r" & Pooled & -- & %d & %d & %s / %s \\" % (v["n_pos"], v["n_neg"], f3(v["sens"]), f3(v["spec"])))
    v = d["heldout_splits_2_5"]
    rows.append(r" \SetCell[c=6]{l} Split-1 threshold of Table~\ref{tab:app_tau} on splits 2 to 5 (same cells, in-distribution) & & & & & \\")
    rows.append(r" & All models & %s & %d & %d & %s / %s \\" % (f3(d["tau_split1_agreement"]), v["n_pos"], v["n_neg"], f3(v["sens"]), f3(v["spec"])))
    out["tb_app_qr_heldout.tex"] = h + r"""\begin{table}[tp]
\centering
\caption{\label{tab:app_qr_heldout}Held-out evaluation of the operating threshold of rule R1 in setting D under L80, post hoc (outside the pre-registration). For each held-out model or dataset, the threshold on the agreement maximizes the Youden index on split 1 of the remaining checkpoints and is applied to splits 2 to 5 of the held-out unit. Collapsed and healthy count checkpoint-settings of the held-out unit on splits 2 to 5. The last row applies the split-1 threshold of Table~\ref{tab:app_tau} to splits 2 to 5 of the same model-dataset cells.}
\footnotesize
\begin{tblr}{colspec={X[0.3,l] X[1.6,l] X[1,c] X[0.9,c] X[0.9,c] X[1.5,c]}, width=\linewidth, colsep=2pt, rowsep=0pt}
\hline
 & Held out & Threshold & Collapsed & Healthy & Sensitivity / specificity \\
\hline
%s
\hline
\end{tblr}
\end{table}
""" % "\n".join(rows)

    # (3) per model, all splits, split-1 threshold
    rows = []
    for m, mn in MODELS:
        v = d["per_model_all_splits"][m]
        rows.append(r" %s & %d & %d of %d & %d of %d \\" % (mn, v["n"], v["collapsed_flagged"], v["collapsed"], v["intact_flagged"], v["intact"]))
    tot = {k: sum(d["per_model_all_splits"][m][k] for m, _ in MODELS) for k in ("n", "collapsed", "collapsed_flagged", "intact", "intact_flagged")}
    rows.append(r" All & %d & %d of %d & %d of %d \\" % (tot["n"], tot["collapsed_flagged"], tot["collapsed"], tot["intact_flagged"], tot["intact"]))
    assert tot["n"] == 987 and tot["collapsed"] == 398
    out["tb_app_qr_model.tex"] = h + r"""\begin{table}[tp]
\centering
\caption{\label{tab:app_qr_model}Flags of rule R1 per model in setting D under L80, over all five splits, at the threshold of 0.738 chosen post hoc on split 1 (outside the pre-registration). Checkpoint-settings count each checkpoint under w4, a6, and l50. Split 1 is the selection split, so these counts are descriptive.}
\footnotesize
\begin{tblr}{colspec={X[1.4,l] X[1.2,c] X[1.6,c] X[1.6,c]}, width=\linewidth, colsep=2pt}
\hline
 Model & Checkpoint-settings & Collapsed and flagged & Healthy and flagged \\
\hline
%s
\hline
\end{tblr}
\end{table}
""" % "\n".join(rows)

    # (4) misses and false alarms on splits 2-5
    rows = []
    mt = {o: 0 for o, _ in OPS}; ft = {o: 0 for o, _ in OPS}
    for m, mn in MODELS:
        mi = d["missed"]["by_model_setting"].get(m, {}); fa = d["false_alarms"]["by_model_setting"].get(m, {})
        for o, _ in OPS:
            mt[o] += mi.get(o, 0); ft[o] += fa.get(o, 0)
        rows.append(r" %s & %s & %s \\" % (mn, " & ".join(str(mi.get(o, 0)) for o, _ in OPS), " & ".join(str(fa.get(o, 0)) for o, _ in OPS)))
    rows.append(r" All & %s & %s \\" % (" & ".join(str(mt[o]) for o, _ in OPS), " & ".join(str(ft[o]) for o, _ in OPS)))
    lo, hi = d["missed"]["R_range"]
    out["tb_app_qr_miss.tex"] = h + r"""\begin{table}[tp]
\centering
\caption{\label{tab:app_qr_miss}Missed collapses and false alarms of rule R1 on splits 2 to 5 in setting D under L80, by model and operator, at the threshold of 0.738 chosen post hoc on split 1 (outside the pre-registration). A missed collapse is a checkpoint-setting with retention below 0.8 that is not flagged, and a false alarm is a flagged checkpoint-setting with retention of at least 0.8. The %d missed collapses have retentions from %.2f to %.2f.}
\footnotesize
\begin{tblr}{colspec={X[1.4,l] X[0.7,c] X[0.7,c] X[0.7,c] X[0.7,c] X[0.7,c] X[0.7,c]}, width=\linewidth, colsep=2pt}
\hline
 & \SetCell[c=3]{c} Missed collapses & & & \SetCell[c=3]{c} False alarms & & \\
 Model & w4 & a6 & l50 & w4 & a6 & l50 \\
\hline
%s
\hline
\end{tblr}
\end{table}
""" % (d["missed"]["n"], lo, hi, "\n".join(rows))
    assert sum(mt.values()) == 29 and sum(ft.values()) == 43
    for name, tex in out.items():
        if "--check" in sys.argv:
            print(tex)
        else:
            io.open(os.path.join(ROOT, "tables", name), "w", encoding="utf8", newline="\n").write(tex)
            print("wrote", name)


if __name__ == "__main__":
    main()
