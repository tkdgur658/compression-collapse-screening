# Generate tables/tb_tiling_fives.tex (Table tab:tiling_fives) from the F5 bootstrap output only.
# Source: results/f5/F5_BOOT.json (written once by f5_summary.py, PREREG_F5 sec. 3-4, all sec. 7 sha OK).
# Usage: python tools/gen_tab_tiling.py   (run from manuscript_cleanup/)
import json, os, sys, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.normpath(os.path.join(ROOT, "..", "results", "f5", "F5_BOOT.json"))
OUT = os.path.join(ROOT, "tables", "tb_tiling_fives.tex")
EXPECTED_SHA = "0a0d39259865b0591ddd4cc939dfc963012a55fc8042da920e24a5fe609ab4e4"

MODELS = [("pbe", "PBE-Net"), ("ucmnet", "UCMNet"), ("utanet", "UTANet"), ("maresunet", "MAResUNet")]
ROWS = [("full_fp32", "Full image"), ("rs256_fp32", "Resize 256"), ("rs512_fp32", "Resize 512"), ("rs1024_fp32", "Resize 1024"),
        ("tile_p256_o0_fp32", "Tiles 256, 0\\%"), ("tile_p256_o50_fp32", "Tiles 256, 50\\%"),
        ("tile_p512_o0_fp32", "Tiles 512, 0\\%"), ("tile_p512_o50_fp32", "Tiles 512, 50\\%")]


def f3(x):
    return f"{x:.3f}"


def main():
    raw = open(SRC, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != EXPECTED_SHA:
        sys.exit(f"F5_BOOT.json sha {sha} differs from the frozen output {EXPECTED_SHA}")
    d = json.loads(raw)
    assert d["sha_valid"] is True
    L = ["% Generated by tools/gen_tab_tiling.py from results/f5/F5_BOOT.json (sha 0a0d3925...). Do not edit by hand.",
         "\\begin{table}[t]", "\\centering",
         "\\caption{\\label{tab:tiling_fives}Detail preservation on FIVES ($2048\\times2048$, 100 validation images, medians, fp32). "
         "Absolute values precede the ratio to full-image inference of the same model, with a paired percentile bootstrap 95\\% confidence interval. "
         "Seam is the clDice ratio of the $\\pm8$-pixel band to the tile interior relative to full-image inference on the same grid. "
         "Tiles $k$, $p$\\% denotes patches of $k$ pixels with $p$\\% overlap. Yes marks a variant that fits the budget.}",
         "\\scriptsize",
         "\\begin{tblr}{colspec={Q[l] Q[l] Q[c] Q[c] Q[c] Q[c] Q[c] Q[c] Q[c]}, colsep=3pt, rowsep=0.3pt}",
         "\\hline",
         " Model & Variant & Peak (MiB) & Thin clDice & Dice & Ratio [95\\% CI] & Seam & 2 GiB & 0.5 GiB \\\\",
         "\\hline"]
    for m, name in MODELS:
        V = d["models"][m]["variants"]
        for i, (vn, label) in enumerate(ROWS):
            v = V[vn]
            assert v["status"] == "ok" and v["nonfinite"] == 0, (m, vn)
            thin = f3(v["median"]["thin3_cldice"][0]); dice = f3(v["median"]["dice"][0])
            if vn == "full_fp32":
                ratio = "1.000"
            else:
                r = v["ratio"]; ratio = f"{f3(r[0])} [{f3(r[1])}, {f3(r[2])}]"
            seam = f3(v["seam"]["s"][0]) if v.get("seam") else "--"
            ex = ["Yes" if v["exec"][b] else "No" for b in ("2 GiB", "0.5 GiB")]
            L.append(f" {name if i == 0 else ''} & {label} & {v['peak_alloc_mib']:.0f} & {thin} & {dice} & {ratio} & {seam} & {ex[0]} & {ex[1]} \\\\")
        L.append("\\hline")
    L += ["\\end{tblr}", "\\end{table}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
