def main():
    sums = {}
    for l in io.open(os.path.join(REL, "SHA256SUMS.txt"), encoding="utf8"):
        h, n = l.split(None, 1)
        sums[n.strip().lstrip("*")] = h
    assert set(sums) == set(d[0] for d in DOCS), sorted(set(sums) ^ set(d[0] for d in DOCS))
    rows = []
    for n, what, where in DOCS:
        h = hashlib.sha256(open(os.path.join(REL, n), "rb").read()).hexdigest()
        assert h == sums[n], n
        rows.append(r" \texttt{%s} & %s & %s & %s \\" % (n.replace("_", r"\_"), h[:8], what, where))
    tex = r"""%% GENERATED by tools/gen_prereg_table.py from prereg/original/SHA256SUMS.txt (hashes re-computed), do not edit by hand.
\begin{table*}[tp]
\centering
\caption{\label{tab:app_prereg}Pre-registration documents, addenda, amendments, and prediction checks, supplied verbatim in the supplementary folder \texttt{prereg\_release} and in the repository at [repository URL], with their full sha256 values. The table gives the first eight hexadecimal digits of each sha256.}
\scriptsize
\begin{tblr}{colspec={Q[l] Q[l] X[2.4,l] X[1.4,l]}, width=\textwidth, colsep=2pt, rowsep=0pt}
\hline
 Document & sha256 & What it fixes & Reported in \\
\hline
%s
\hline
\end{tblr}
\end{table*}
""" % "\n".join(rows)
    io.open(OUT, "w", encoding="utf8", newline="\n").write(tex)
    print("wrote", os.path.normpath(OUT), len(rows))


if __name__ == "__main__":
    main()
