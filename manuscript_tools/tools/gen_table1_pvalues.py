"""Pass 32 (journal review 2, item A-5, [internal decision] = [id], 2026-10-16): all 60 comparisons of Table 1
(PBE-Net minus each baseline, per dataset) with the mean paired difference, its 95% t interval over the five splits
(df = 4), the raw p and the Holm-adjusted p -> tables/tb_app_table1_p.tex.

Same data and test as tools/sig_table1.py (TABLE1_SIG.md), whose load() and holm() are imported unchanged:
per-image test IoU of <workspace>/data/main/<model>/<dataset>/k<split>/results.json, two-sided paired t-test
(scipy.stats.ttest_rel, pairing by split index), Holm step-down over the ten baselines within each dataset.
Run:  python -s tools/gen_table1_pvalues.py
"""
import io, os, sys
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import sig_table1 as S

OUT = os.path.join(HERE, "..", "tables", "tb_app_table1_p.tex")
DSN = {"PH2": "PH2", "isic17": "ISIC 2017", "isic18": "ISIC 2018", "kvasir": "Kvasir-SEG", "cvc": "CVC-ClinicDB", "etis": "ETIS-Larib"}
NAME = dict(S.ROWS); NAME["egeunet"] = "EGE-UNet"


def fp(x):
    return "$<$0.0001" if x < 1e-4 else "%.4f" % x


def main():
    cells = S.load()
    rows = []
    nsig = 0
    for d, _ in S.DS:
        others = [r for r, _ in S.ROWS if r != "pbe"]
        diffs = [cells[("pbe", d)] - cells[(r, d)] for r in others]
        p = [stats.ttest_rel(cells[("pbe", d)], cells[(r, d)]).pvalue for r in others]
        pa = S.holm(p)
        tq = stats.t.ppf(0.975, 4)
        for j, (r, df, pr, pp) in enumerate(zip(others, diffs, p, pa)):
            m = df.mean(); se = df.std(ddof=1) / np.sqrt(len(df))
            sig = pp < S.ALPHA
            nsig += sig
            rows.append((DSN[d] if j == 0 else "", NAME[r], "%+.3f" % m, "[%+.3f, %+.3f]" % (m - tq * se, m + tq * se),
                         fp(pr), ("\\textbf{%s}" if sig else "%s") % fp(pp)))
    assert len(rows) == 60 and nsig == 28, nsig  # TABLE1_SIG.md: 28 of 60 significant after Holm
    # Pass 32 layout: two tables of 30 rows (datasets 1-3 and 4-6); the two-up layout of one table was too wide.
    parts = []
    for part, (lab, cap) in enumerate([
        ("tab:app_table1_p", r"All 60 comparisons of Table~\ref{tab:main_polyp}, part 1 (dermoscopy): mean paired difference of per-image test IoU (PBE-Net minus baseline) over the five splits, its 95\%% t interval ($\mathrm{df}=4$), the raw two-sided paired t-test p value, and the Holm-adjusted p value over the ten baselines of each dataset. Bold marks an adjusted p below 0.05 (%d of 60 over both parts). With five splits per comparison, power is low, so an adjusted p above 0.05 does not show that two means are equal." % nsig),
        ("tab:app_table1_p2", r"All 60 comparisons of Table~\ref{tab:main_polyp}, part 2 (colonoscopy), with the columns of Table~\ref{tab:app_table1_p}.")]):
        body = "\n".join(" " + " & ".join(r) + r" \\" for r in rows[30 * part:30 * part + 30])
        parts.append(r"""\begin{table}[tp]
\centering
\caption{\label{%s}%s}
\scriptsize
\begin{tblr}{colspec={Q[l] Q[l] Q[r] Q[c] Q[r] Q[r]}, colsep=3pt, rowsep=0pt}
\hline
 Dataset & Baseline & Diff. & 95\%% CI & p & Holm p \\
\hline
%s
\hline
\end{tblr}
\end{table}
""" % (lab, cap, body))
    tex = "%% GENERATED by tools/gen_table1_pvalues.py (imports load() and holm() of tools/sig_table1.py, source <workspace>/data/main results.json, same test as TABLE1_SIG.md), do not edit by hand.\n" + "\n".join(parts)
    io.open(OUT, "w", encoding="utf8", newline="\n").write(tex)
    print("wrote", os.path.normpath(OUT), "significant", nsig)


if __name__ == "__main__":
    main()
