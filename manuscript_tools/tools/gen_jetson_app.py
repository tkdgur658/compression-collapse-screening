# Generate the Jetson Nano attempt table (Appendix app:jetson) and the Table 2 Jetson column marks from
# results/jetson/JETSON_RESULT.json only (PREREG_JETSON.md frozen sha 6afdf445; no model reportable).
# Usage: python tools/gen_jetson_app.py   (run from manuscript_cleanup/)  -> tables/tb_app_jetson.tex, prints the column marks.
import json, os, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.normpath(os.path.join(ROOT, "..", "results", "jetson", "JETSON_RESULT.json"))
OUT = os.path.join(ROOT, "tables", "tb_app_jetson.tex")
EXPECTED = "c7ff2ee6"
ORDER = ["pbe", "maresunet", "utanet", "mk_unet", "mhorunet", "tinyunet", "ucmnet", "lbunet", "cmunext", "egeunet", "malunet"]
DISPLAY = {"pbe": "PBE-Net", "maresunet": "MAResUNet", "utanet": "UTANet", "mk_unet": "MK-UNet", "mhorunet": "MHorUNet",
           "tinyunet": "TinyU-Net", "ucmnet": "UCMNet", "lbunet": "LB-UNet", "cmunext": "CMUNeXt", "egeunet": "EGE-UNet", "malunet": "MALUNet"}


def kind(v):
    r = v.get("reason") or ""
    if r.startswith("unstable"):
        return "a", "Engine built and ran, clock changed during every block"
    if r.startswith("TensorRT"):
        return "b", "TensorRT 8.2.1 rejected the ONNX graph"
    if r.startswith("ONNX opset 11 export failed"):
        return "c", "No ONNX opset 11 export of an operator"
    raise ValueError(r)


def main():
    raw = open(SRC, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    assert sha.startswith(EXPECTED), sha
    d = json.loads(raw)
    M = d["models"]
    assert all(M[k]["status"] == "n.m." for k in ORDER)
    L = ["% Generated by tools/gen_jetson_app.py from results/jetson/JETSON_RESULT.json (sha ed3e719e...). Do not edit by hand.",
         "\\begin{table}[t]", "\\centering",
         "\\caption{\\label{tab:app_jetson}Jetson Nano attempt for the eleven models (TensorRT FP16, fused graph, ONNX opset 11, warm-up 10 and 50 timed runs). "
         "No model met the frozen measurement rule. The medians of the three discarded blocks are not reportable under the frozen rule (clock changed during the block) and are listed only as a record.}",
         "\\footnotesize",
         "\\begin{tblr}{colspec={Q[l] Q[c] X[l] Q[c]}, width=\\linewidth, colsep=3pt}",
         "\\hline",
         " Model & Status & Reason & Discarded medians (ms) \\\\",
         "\\hline"]
    marks = {}
    for k in ORDER:
        v = M[k]
        code, text = kind(v)
        marks[k] = code
        if code == "a":
            meds = [v["attempts"][a]["discarded_block_stats"]["median_ms"] for a in v["discarded_attempts"]]
            med = " / ".join(f"{x:.1f}" for x in meds)
        else:
            med = "--"
        L.append(f" {DISPLAY[k]} & n.m.$^{code}$ & {text} & {med} \\\\")
    L += ["\\hline", "\\end{tblr}", "\\end{table}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print(json.dumps(marks))


if __name__ == "__main__":
    main()
