"""Regenerate Table 1 (tables/tb_main.tex) and TABLE1_DIFF.md from protocol-v1 result files.

Sources (read only):
  ../data/main/<model>/<dataset>/k<split>/results.json   (local copy of pbe_seg/runs/main; test['iou'] = per-image IoU)
  ../../paper_out_v1/paper_out/tb_main.tex               (v1 table generated by code/pbe_seg/tools/make_tables.py; baseline cells are cross-checked against it)
  tools/tb_main_before.tex.txt                               (copy of the legacy table, taken on the first run)
Rounding: mean and sample std (ddof=1) of the per-split test IoU, 3 decimals (same as make_tables.py and the old table).
Proposed model: only splits with status == complete exist (20 of 30 runs); its cells are means over those splits only.
"""
import glob
import json
import os
import re
import shutil

import numpy as np

import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sig_table1  # same directory; paired t-test + Holm as in code/pbe_seg/tools/make_tables.py

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
WS = os.path.abspath(os.path.join(ROOT, "..", ".."))  # workspace
RUNS = os.path.abspath(os.path.join(ROOT, "..", "results", "table1_runs"))
V1TEX = os.path.join(ROOT, "reference", "tb_main_v1.tex")
OLD = os.path.join(HERE, "tb_main_before.tex.txt")
NEW = os.path.join(ROOT, "tables", "tb_main.tex")
if not os.path.exists(OLD):
    shutil.copy(NEW, OLD)

# Pass 11 naming rule: print "PBE-Net", "EGE-UNet" and "ETIS-Larib" exactly as the manuscript uses them after review 1
# (tb_main.tex, tb_eff.tex, text). parse_table() and the row matching strip hyphens, so these labels still match
# paper_out_v1/tb_main.tex ("EGEUNet") and the previous tb_main.tex. The first element is the result-folder key.
# NOTE: the caption below still differs from the hand-edited caption in tables/tb_main.tex (review 1 moved the
# low-power sentence to Section 4b), so do not copy a regenerated tb_main.tex over the current one without a diff.
ROWS = [("pbe", "PBE-Net"), ("maresunet", "MAResUNet"), ("utanet", "UTANet"), ("mk_unet", "MK-UNet"),
        ("mhorunet", "MHorUNet"), ("tinyunet", "TinyU-Net"), ("ucmnet", "UCMNet"), ("lbunet", "LB-UNet"),
        ("cmunext", "CMUNeXt"), ("egeunet", "EGE-UNet"), ("malunet", "MALUNet")]
DS = [("PH2", "PH2"), ("isic17", "ISIC 2017"), ("isic18", "ISIC 2018"), ("kvasir", "Kvasir-SEG"),
      ("cvc", "CVC-ClinicDB"), ("etis", "ETIS-Larib")]


def load():
    v = {}
    for f in glob.glob(os.path.join(RUNS, "*", "*", "k*", "results.json")):
        r = json.load(open(f))
        if r.get("status") != "complete":
            continue
        p = f.replace("\\", "/").split("/")
        v[(p[-4], p[-3], int(p[-2][1:]))] = r["test"]["iou"]
    return v


def parse_table(tex):
    """{row label without hyphen: [(mean, std) x 6]} from a tblr table"""
    out = {}
    for line in tex.split("\n"):
        m = re.match(r"\s*([A-Za-z\-]+) & (.*) \\\\\s*$", line)
        if not m:
            continue
        cells = re.findall(r"(\d\.\d{3}) \$\\pm\$ (\d\.\d{3})", m.group(2))
        if len(cells) == 6:
            out[m.group(1).replace("-", "")] = [(float(a), float(b)) for a, b in cells]
    return out


vals = load()
splits, new = {}, {}
for r, _ in ROWS:
    for d, _ in DS:
        s = sorted(k for (rr, dd, k) in vals if rr == r and dd == d)
        x = np.array([vals[(r, d, k)] for k in s])
        splits[(r, d)] = s
        new[(r, d)] = (round(float(x.mean()), 3), round(float(x.std(ddof=1)), 3), len(s))

v1 = parse_table(open(V1TEX, encoding="utf8").read())
mism = []
for r, name in ROWS[1:]:
    key = name.replace("-", "")
    for i, (d, _) in enumerate(DS):
        a = (new[(r, d)][0], new[(r, d)][1])
        b = v1[key][i]
        if abs(a[0] - b[0]) > 1e-9 or abs(a[1] - b[1]) > 1e-9:
            mism.append((name, d, a, b))
print("baseline cells differing from paper_out_v1/tb_main.tex:", mism)
assert not mism and all(new[(r, d)][2] == 5 for r, _ in ROWS[1:] for d, _ in DS)

old = parse_table(open(OLD, encoding="utf8").read())

best = {d: max(new[(r, d)][0] for r, _ in ROWS) for d, _ in DS}
PBE_FULL = all(new[("pbe", d)][2] == 5 for d, _ in DS)  # pass 4: all 30 Proposed runs complete -> no dagger
PH = "" if PBE_FULL else r"\phantom{$^{\dagger}$}"
cap = (r"\caption{\label{tab:main_polyp}Per-image IoU of the evaluated models on PH2, ISIC 2017, ISIC 2018, Kvasir-SEG, CVC-ClinicDB, and ETIS-Larib "
       r"under protocol v1 (mean $\pm$ sample standard deviation over splits). The ten baselines are averaged over five splits. "
       r"$^{\dagger}$ The Proposed row is averaged over the completed splits only (PH2 4, ISIC 2017 3, ISIC 2018 4, Kvasir-SEG 3, CVC-ClinicDB 3, ETIS-Larib 3 of 5); "
       r"the remaining runs are pending. Bold type marks the highest mean in each dataset.}")
SIGCELLS, SIGRES = sig_table1.compute()
if PBE_FULL:
    cap = (r"\caption{\label{tab:main_polyp}Per-image IoU of the evaluated models on PH2, ISIC 2017, ISIC 2018, Kvasir-SEG, CVC-ClinicDB, and ETIS-Larib "
           r"under protocol v1 (mean $\pm$ sample standard deviation over five splits). Bold type marks the highest mean in each dataset. "
           r"$^{\blacktriangledown}$ marks a baseline mean significantly lower than that of the Proposed model "
           r"(two-sided paired $t$-test over the five splits, Holm correction over the ten baselines within each dataset, $\alpha=0.05$). "
           r"With five splits the test has low power, and an unmarked cell means that no difference was established, not that the means are equal.}")
CHK = ("% Closed (pass 4): Table 1 regenerated by tools/gen_table1.py from protocol-v1 result files (all 11 models x 6 datasets x 5 splits; Proposed splits 1-4 or 1-3 from pbe_seg/runs/main, the rest from the fill-in queue <WORK>/pbe_v1_fill, verified identical config/code). Significance marks from tools/sig_table1.py (same paired t-test and Holm as code/pbe_seg/tools/make_tables.py)."
       if PBE_FULL else None)
out = [CHK or "% CHECK: Table 1 regenerated by tools/gen_table1.py from protocol-v1 result files (<workspace>/data/main = copy of pbe_seg/runs/main; baseline cells cross-checked cell by cell against paper_out_v1/paper_out/tb_main.tex). Proposed cells are partial-split means (20 of 30 runs complete). Re-run the script when the remaining 10 pbe runs finish, then drop the dagger and add significance marks via code/pbe_seg/tools/make_tables.py.",
       r"\begin{table*}[!t]", r"\centering", cap, "",
       r"\begin{tblr}{colspec={ X[c,1] X[c,1] X[c,1] X[c,1] X[c,1] X[c,1] X[c,1] }, width=\textwidth, colsep=0.5pt}",
       r"\hline", r" Model Name & PH2 & ISIC 2017 & ISIC 2018 & Kvasir-SEG & CVC-ClinicDB & ETIS-Larib \\", r"\hline"]
for r, name in ROWS:
    cs = []
    for d, _ in DS:
        m, s, n = new[(r, d)]
        t = f"{m:.3f} $\\pm$ {s:.3f}"
        if m == best[d]:
            t = r"\textbf{" + t + "}"
        mk = SIGRES.get((r, d), {}).get("mark", "") if PBE_FULL else ""
        PHS = r"\phantom{$^{\blacktriangledown}$}"
        t += {"down": r"$^{\blacktriangledown}$", "up": r"$^{\blacktriangle}$"}.get(mk, PHS if PBE_FULL else "")
        if r == "pbe" and not PBE_FULL:
            t += r"$^{\dagger}$"
        cs.append("{" + t + "}")
    out.append(name + " & " + " & ".join(cs) + r" \\")
out += [r"\hline", r"\end{tblr}", r"\end{table*}"]
open(NEW, "w", encoding="utf8", newline="\n").write("\n".join(out))


def ranks(col):
    rk = {r: 1 + sum(col[o] > col[r] for o, _ in ROWS) for r, _ in ROWS}
    first = [nm for r, nm in ROWS if rk[r] == 1]
    return rk, "/".join(first)


D = ["# TABLE1_DIFF: Table 1 before (legacy cells in manuscript_bspc) -> after (protocol v1 result files)\n",
     "Generated by `tools/gen_table1.py` (do not edit by hand). Format: `before -> after (delta of mean)`, mean +- sample std, 3 decimals.\n",
     "Sources: `<workspace>/data/main/*/*/k*/results.json` (copy of `pbe_seg/runs/main`, `test.iou` = per-image IoU, status complete only). "
     "The 10 baseline cells equal `paper_out_v1/paper_out/tb_main.tex` cell by cell (asserted in the script). "
     + ("All 30 Proposed runs are complete (pass 4): every cell is a five-split mean.\n" if PBE_FULL else
        "The Proposed model has only 20 of 30 v1 runs complete (`paper_out_v1/paper_out/status.txt`): its `after` cells are means over the completed splits (n shown), NOT five-split means.\n"),
     ("Significance marks: from `tools/sig_table1.py` (paired t-test over splits, Holm within dataset, see `TABLE1_SIG.md`); the old triangles had no traceable test and were removed in pass 2.\n" if PBE_FULL else
      "Significance marks (down-triangles) of the old table are removed: they had no traceable test, and a paired test needs all five splits of the Proposed model.\n")]
D.append("| Model | " + " | ".join(n for _, n in DS) + " |")
D.append("|" + "---|" * (len(DS) + 1))
nchg = ncell = nmean = 0
for r, name in ROWS:
    cs = []
    for i, (d, _) in enumerate(DS):
        ob = old[name.replace("-", "")][i]
        nb = new[(r, d)]
        ncell += 1
        ch = (abs(ob[0] - nb[0]) > 1e-9) or (abs(ob[1] - nb[1]) > 1e-9)
        nchg += ch
        nmean += abs(ob[0] - nb[0]) > 1e-9
        n = f" [n={nb[2]}]" if r == "pbe" else ""
        cs.append(f"{ob[0]:.3f}+-{ob[1]:.3f} -> {nb[0]:.3f}+-{nb[1]:.3f} ({nb[0]-ob[0]:+.3f}){n}" if ch
                  else f"{nb[0]:.3f}+-{nb[1]:.3f} (same){n}")
    D.append(f"| {name} | " + " | ".join(cs) + " |")
D.append(f"\nCells changed (mean or std differs): **{nchg} of {ncell}** (11 models x 6 datasets). Cells with a changed mean: {nmean} of {ncell}.\n")

D.append("## Rank of the Proposed model per column (1 = highest mean among 11 models)\n")
D.append("`rank after` = Table 1 as shown. "
         "`matched` = all 11 models recomputed on exactly the splits the Proposed model completed (fairer, see table below).\n")
D.append("| Dataset | rank before | first before | rank after | first after | Proposed minus best baseline (after) | matched rank | matched first |")
D.append("|---|---|---|---|---|---|---|---|")
notfirst = notfirst_m = 0
facts = []
for i, (d, dn) in enumerate(DS):
    bcol = {r: old[nm.replace("-", "")][i][0] for r, nm in ROWS}
    acol = {r: new[(r, d)][0] for r, _ in ROWS}
    rb, fb = ranks(bcol)
    ra, fa = ranks(acol)
    sp = splits[("pbe", d)]
    mcol = {r: round(float(np.mean([vals[(r, d, k)] for k in sp])), 3) for r, _ in ROWS}
    rm, fm = ranks(mcol)
    bestb = max((acol[r], nm) for r, nm in ROWS[1:])
    gap = acol["pbe"] - bestb[0]
    notfirst += ra["pbe"] != 1
    notfirst_m += rm["pbe"] != 1
    D.append(f"| {dn} | {rb['pbe']} | {fb} | {ra['pbe']} | {fa} | {gap:+.3f} (best baseline {bestb[1]} {bestb[0]:.3f}) | {rm['pbe']} (n={len(sp)}) | {fm} |")
    facts.append((dn, ra["pbe"], fa, gap, bestb, rm["pbe"], fm, acol["pbe"]))
D.append(f"\nProposed first before: 6 of 6 columns. After (Table 1 as shown): first in {6-notfirst} of 6, **not first in {notfirst}**. "
         f"On matched splits: first in {6-notfirst_m} of 6, not first in {notfirst_m}.\n")
D.append("## Matched-split means (all 11 models on the splits the Proposed model completed)\n")
D.append("| Model | " + " | ".join(f"{n} (splits {','.join(map(str, splits[('pbe', d)]))})" for d, n in DS) + " |")
D.append("|" + "---|" * (len(DS) + 1))
for r, nm in ROWS:
    D.append(f"| {nm} | " + " | ".join(f"{np.mean([vals[(r, d, k)] for k in splits[('pbe', d)]]):.3f}" for d, _ in DS) + " |")
D.append("\n## Row means over the six datasets (Table 1 as shown)\n")
D.append("| Model | mean before | mean after |")
D.append("|---|---|---|")
for r, nm in ROWS:
    D.append(f"| {nm} | {np.mean([old[nm.replace("-", "")][i][0] for i in range(6)]):.3f} | {np.mean([new[(r,d)][0] for d,_ in DS]):.3f} |")
open(os.path.join(ROOT, "TABLE1_DIFF.md"), "w", encoding="utf8", newline="\n").write("\n".join(D) + "\n")
print("changed", nchg, "of", ncell, "means changed", nmean, "notfirst", notfirst, "matched notfirst", notfirst_m)
for f in facts:
    print(f)
