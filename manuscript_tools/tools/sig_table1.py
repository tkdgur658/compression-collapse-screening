"""Significance test for Table 1, reproducing code/pbe_seg/tools/make_tables.py on the local result files.

Same test as make_tables.py: for each dataset, two-sided paired t-test (scipy.stats.ttest_rel) over the five splits,
each baseline against the Proposed model (pairing by split index), Holm step-down correction over the ten baseline
comparisons within that dataset, alpha = 0.05. Mark: 'down' = baseline significantly lower than Proposed,
'up' = significantly higher. Source: ../data/main/<model>/<dataset>/k<split>/results.json, status complete, test['iou'].
Run: python tools/sig_table1.py   (writes TABLE1_SIG.md; gen_table1.py imports compute()).
"""
import glob
import json
import os

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
RUNS = os.path.abspath(os.path.join(ROOT, "..", "results", "table1_runs"))
ROWS = [("pbe", "Proposed"), ("maresunet", "MAResUNet"), ("utanet", "UTANet"), ("mk_unet", "MK-UNet"),
        ("mhorunet", "MHorUNet"), ("tinyunet", "TinyU-Net"), ("ucmnet", "UCMNet"), ("lbunet", "LB-UNet"),
        ("cmunext", "CMUNeXt"), ("egeunet", "EGEUNet"), ("malunet", "MALUNet")]
DS = [("PH2", "PH2"), ("isic17", "ISIC 2017"), ("isic18", "ISIC 2018"), ("kvasir", "Kvasir-SEG"),
      ("cvc", "CVC-ClinicDB"), ("etis", "ETIS-LaribPolypDB")]
SPLITS = [1, 2, 3, 4, 5]
ALPHA = 0.05


def holm(p):  # identical to make_tables.py
    p = np.asarray(p, float); order = np.argsort(p); adj = np.empty_like(p); run = 0.0
    for i, idx in enumerate(order):
        run = max(run, min(1.0, (len(p) - i) * p[idx])); adj[idx] = run
    return adj


def load(metric="iou"):
    vals = {}
    for f in glob.glob(os.path.join(RUNS, "*", "*", "k*", "results.json")):
        r = json.load(open(f))
        if r.get("status") != "complete":
            continue
        row = f.replace("\\", "/").split("/")[-4]
        vals[(row, r["config"]["dataset"], r["config"]["split"])] = r["test"][metric]
    cells = {}
    for row, _ in ROWS:
        for d, _ in DS:
            v = [vals.get((row, d, k)) for k in SPLITS]
            assert all(x is not None for x in v), (row, d)
            cells[(row, d)] = np.array(v, float)
    return cells


def compute():
    cells = load()
    res = {}  # (baseline, dataset) -> dict
    for d, _ in DS:
        others = [r for r, _ in ROWS if r != "pbe"]
        tt = [stats.ttest_rel(cells[("pbe", d)], cells[(r, d)]) for r in others]
        p = [t.pvalue for t in tt]
        padj = holm(p)
        for r, t, pr, pa in zip(others, tt, p, padj):
            diff = cells[("pbe", d)].mean() - cells[(r, d)].mean()
            mark = ("down" if -diff < 0 else "up") if pa < ALPHA else ""
            res[(r, d)] = dict(diff=diff, t=float(t.statistic), p=float(pr), padj=float(pa), mark=mark)
    return cells, res


if __name__ == "__main__":
    cells, res = compute()
    name = dict(ROWS)
    L = ["# TABLE1_SIG: paired t-test, Proposed vs each baseline (generated by `tools/sig_table1.py`)\n",
         "Reproduces `code/pbe_seg/tools/make_tables.py` on `<workspace>/data/main` (not run against the server layout): per-image IoU `test.iou` of the five splits, "
         "two-sided paired t-test (`scipy.stats.ttest_rel`, df = 4, pairing by split index), Holm step-down over the 10 baseline comparisons within each dataset, alpha = 0.05. "
         "Mark in the table: a baseline cell is marked only if it is significantly lower than Proposed after Holm (a significantly higher baseline would get the up mark). "
         "n = 5 splits per cell, so power is low.\n",
         "Cell format: mean difference (Proposed minus baseline), raw p, Holm-adjusted p. `*` = significant after Holm.\n",
         "| Baseline | " + " | ".join(n for _, n in DS) + " |", "|" + "---|" * 7]
    for r, nm in ROWS[1:]:
        cs = []
        for d, _ in DS:
            x = res[(r, d)]
            cs.append(f"{x['diff']:+.3f}, {x['p']:.4f}, {x['padj']:.4f}" + (" *" if x["mark"] else ""))
        L.append(f"| {nm} | " + " | ".join(cs) + " |")
    L.append("\n## Counts after Holm (out of 10 baselines per dataset, 60 comparisons in total)\n")
    L.append("| Dataset | Proposed mean | best baseline (mean) | Proposed minus best baseline | std of Proposed | significantly lower baselines | significantly higher baselines |")
    L.append("|---|---|---|---|---|---|---|")
    tot_dn = tot_up = 0
    for d, dn in DS:
        pm = cells[("pbe", d)].mean(); ps = cells[("pbe", d)].std(ddof=1)
        bb = max((cells[(r, d)].mean(), r) for r, _ in ROWS[1:])
        dn_ = sum(res[(r, d)]["mark"] == "down" for r, _ in ROWS[1:])
        up_ = sum(res[(r, d)]["mark"] == "up" for r, _ in ROWS[1:])
        tot_dn += dn_; tot_up += up_
        L.append(f"| {dn} | {pm:.3f} | {name[bb[1]]} ({bb[0]:.3f}) | {pm-bb[0]:+.3f} | {ps:.3f} | {dn_} of 10 | {up_} of 10 |")
    L.append(f"\nTotal: {tot_dn} of 60 comparisons significantly lower than Proposed, {tot_up} of 60 significantly higher, after Holm.\n")
    L.append("## Comparison against the best baseline of each dataset\n")
    L.append("| Dataset | best baseline | diff | raw p | Holm p | significant |")
    L.append("|---|---|---|---|---|---|")
    for d, dn in DS:
        bb = max((cells[(r, d)].mean(), r) for r, _ in ROWS[1:])[1]
        x = res[(bb, d)]
        L.append(f"| {dn} | {name[bb]} | {x['diff']:+.3f} | {x['p']:.4f} | {x['padj']:.4f} | {'yes' if x['mark'] else 'no'} |")
    open(os.path.join(ROOT, "TABLE1_SIG.md"), "w", encoding="utf8", newline="\n").write("\n".join(L) + "\n")
    print("\n".join(L))
