"""Pass 30 ([internal decision], 2026-10-16): generate tables/tb_app_tau.tex (Appendix app:tau) from the post hoc
operating-threshold result of rule R1 (screen; rule R2 before the Pass 32 renumbering, [internal decision]: caption "rule R2" -> "rule R1").

Source: results/qdeploy/tau/TAU_RESULT.json (sha256 must be 8c7c55e0...4f157), produced by tau_youden.py
(sha256 must be 6d3d99a1...4830) on the frozen F3 QDEPLOY records. The script refuses to write if either hash differs.
Flag direction (tau_youden.py): flag iff collapse score (1 - agreement) >= tau_score, i.e. agreement <= tau_agreement.
The selection split is split 1 (Youden J maximum), splits 2-5 are test splits.

Run:  python -s tools/gen_tau_table.py          (writes tables/tb_app_tau.tex)
      python -s tools/gen_tau_table.py --check  (prints the table, writes nothing)
"""
import hashlib, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
TAU = os.path.normpath(os.path.join(ROOT, "..", "results", "qdeploy", "tau"))
JSON_SHA = "8c7c55e00a4e54c0674f360f6b2e52f888641d6d5c704439ac359d6bc5f4b157"
SCRIPT_SHA = "d75216669ce08c48e60bedcd628b05a1bb58b453492c998f225c8ec08405fbb3"
OUT = os.path.join(ROOT, "tables", "tb_app_tau.tex")


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    jp, sp = os.path.join(TAU, "TAU_RESULT.json"), os.path.join(TAU, "tau_youden.py")
    if sha(jp) != JSON_SHA or sha(sp) != SCRIPT_SHA:
        sys.exit("sha256 mismatch: TAU_RESULT.json %s, tau_youden.py %s" % (sha(jp), sha(sp)))
    d = json.load(open(jp, encoding="utf8"))
    f3 = lambda x: "%.3f" % x
    rows = []
    for lab, thr in (("L80", "0.8"), ("L90", "0.9")):
        o = d[lab]
        # consistency checks of the json itself
        assert abs(o["tau_agreement"] - (1 - o["tau_score"])) < 1e-12
        te = o["test_splits_2_5"]
        assert te["n_pos"] == sum(o["per_split"][k]["n_pos"] for k in "2345")
        assert te["n_neg"] == sum(o["per_split"][k]["n_neg"] for k in "2345")
        n1, p1 = o["n_split1"], o["pos_split1"]
        rows.append(r" \SetCell[c=6]{l} %s (Dice retention below %s), flagged when output agreement $\le$ %s & & & & & \\"
                    % (lab, thr, f3(o["tau_agreement"])))
        rows.append(r" 1 & Selection, $J=%s$ & %d & %d & %s & %s \\" % (f3(o["J_split1"]), p1, n1 - p1,
                                                                   f3(o["sens_split1"]), f3(o["spec_split1"])))
        for k in "2345":
            s = o["per_split"][k]
            rows.append(r" %s & Test & %d & %d & %s & %s \\" % (k, s["n_pos"], s["n_neg"], f3(s["sens"]), f3(s["spec"])))
        rows.append(r" 2--5 & Test, pooled & %d & %d & %s & %s \\" % (te["n_pos"], te["n_neg"], f3(te["sens"]), f3(te["spec"])))
        rows.append(r"\hline" if lab == "L90" else "\\hline\n\\hline")
    excl = ", ".join(sorted(d["excluded"]))
    body = "\n".join(rows)
    tex = r"""%% GENERATED by tools/gen_tau_table.py from results/qdeploy/tau/TAU_RESULT.json (sha256 %s), do not edit by hand.
%% Post hoc (outside the pre-registration). Exact thresholds: L80 agreement %.6f (score %.6f), L90 agreement %.6f (score %.6f). Excluded checkpoint: %s.
\begin{table}[t]
\centering
\caption{\label{tab:app_tau}Post hoc operating threshold of rule R1 in setting D, outside the pre-registration. A checkpoint under one setting is flagged when its output agreement is at most the threshold. The threshold maximizes the Youden index $J$ on split 1 and is applied unchanged to splits 2 to 5. Collapsed and healthy count checkpoint-settings under the checkpoint-level label. Split 4 has 195 checkpoint-settings because one checkpoint is excluded (MALUNet, ISIC 2018).}
\small
\begin{tblr}{colspec={X[0.7,l] X[1.9,l] X[1,c] X[1,c] X[1.1,c] X[1.1,c]}, width=\linewidth, colsep=2pt}
\hline
 Split & Role & Collapsed & Healthy & Sensitivity & Specificity \\
\hline
%s
\end{tblr}
\end{table}
""" % (JSON_SHA, d["L80"]["tau_agreement"], d["L80"]["tau_score"], d["L90"]["tau_agreement"], d["L90"]["tau_score"],
       excl, body)
    if "--check" in sys.argv:
        print(tex)
        return
    io.open(OUT, "w", encoding="utf8", newline="\n").write(tex)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
